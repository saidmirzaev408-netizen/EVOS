// Resolver helper
export const getFoodName = (product, lang = 'uz') => {
  if (!product) return '';
  if (product.name?.[lang]) return product.name[lang];
  if (foodNameTranslations[product.id]?.[lang]) return foodNameTranslations[product.id][lang];
  if (product.name?.ru && (lang === 'kk' || lang === 'tg')) return product.name.ru;
  if (product.name?.en) return product.name.en;
  return product.name?.uz || '';
};

